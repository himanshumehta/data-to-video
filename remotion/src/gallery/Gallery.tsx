// ── Content type labels ─────────────────────────────────────────────────

const CONTENT_TYPE_LABELS: Record<ContentType, string> = {
  "ownership-cost": "Ownership Cost",
  "vehicle-review": "Vehicle Review",
  "owner-verdict": "Owner Verdict",
  "service-bill": "Service Bill",
};

// ── Gallery component ───────────────────────────────────────────────────

export const Gallery: React.FC = () => {
  const [vehicle, setVehicle] = useState<Vehicle>(PLACEHOLDER);
  const [verdictVehicle, setVerdictVehicle] = useState<Vehicle | null>(null);
  const [config, setConfig] = useState<GalleryConfig | null>(null);
  const [loading, setLoading] = useState(true);
  const [jsonOpen, setJsonOpen] = useState(false);
  const [showFinal, setShowFinal] = useState(true);
  const [contentType, setContentType] = useState<ContentType>(
    () => (localStorage.getItem("bnc-gallery-content-type") as ContentType) || "ownership-cost"
  );
  const [format, setFormat] = useState<FormatKey>("9:16");
  const [narrationLang, setNarrationLang] = useState<string>("en");
  const [billData, setBillData] = useState<any | null>(null);

  useEffect(() => {
    Promise.all([loadVehicle(), loadVerdictVehicle(), loadGalleryConfig(), loadBillData()]).then(([v, vv, cfg, bd]) => {
      if (v) setVehicle(v as Vehicle);
      if (vv) setVerdictVehicle(vv as Vehicle);
      if (cfg) {
        setConfig(cfg);
        if (cfg.defaultLang) setNarrationLang(cfg.defaultLang);
      }
      if (bd) setBillData(bd);
      setLoading(false);
    });
  }, []);

  // Each content type uses its own vehicle data -- completely independent
  const activeVehicle = contentType === "owner-verdict"
    ? (verdictVehicle || PLACEHOLDER)
    : vehicle;

  const isBill = contentType === "service-bill";

  return (
    <div style={{ padding: 32, maxWidth: 1400, margin: "0 auto" }}>
      {/* Header */}
      <h1 style={{ fontSize: 28, fontWeight: 800, marginBottom: 4 }}>
        {isBill ? `${billData?.manufacturer_name || ""} ${billData?.vehicle_name || ""}` : `${activeVehicle.brand_name} ${activeVehicle.short_name}`}
        <span style={{ fontSize: 14, fontWeight: 600, color: "#a78bfa", marginLeft: 12 }}>
          {CONTENT_TYPE_LABELS[contentType]}
        </span>
        {SESSION && (
          <span style={{ fontSize: 12, fontWeight: 600, color: "#52525b", marginLeft: 12 }}>
            session: {SESSION}
          </span>
        )}
      </h1>
      <div style={{ color: "#71717a", fontSize: 14, marginBottom: 16, display: "flex", gap: 16 }}>
        <span>Price: <span style={{ color: "#a1a1aa" }}>{activeVehicle.price_formatted}</span></span>
        {contentType !== "owner-verdict" && <span>5yr: <span style={{ color: "#a1a1aa" }}>{activeVehicle.net_5yr_display}</span></span>}
        {contentType === "owner-verdict"
          ? <span>Rating: <span style={{ color: "#a1a1aa" }}>{(activeVehicle as any).overall_rating ?? "\u2014"}/5</span></span>
          : <span>Rating: <span style={{ color: "#a1a1aa" }}>{activeVehicle.expert_rating}/10</span></span>
        }
        {loading && <span style={{ color: "#f59e0b" }}>Loading vehicle data...</span>}
      </div>

      {/* Content type selector */}
      <div style={{ marginBottom: 16, display: "flex", gap: 8 }}>
        {(["ownership-cost", "vehicle-review", "owner-verdict", "service-bill"] as ContentType[]).map((ct) => (
          <button
            key={ct}
            onClick={() => { setContentType(ct); localStorage.setItem("bnc-gallery-content-type", ct); }}
            style={{
              padding: "8px 20px",
              borderRadius: 8,
              border: "1px solid",
              borderColor: contentType === ct ? "#a78bfa" : "#27272a",
              background: contentType === ct ? "rgba(167,139,250,0.12)" : "#18181b",
              color: contentType === ct ? "#a78bfa" : "#71717a",
              fontSize: 13,
              fontWeight: 700,
              cursor: "pointer",
              fontFamily: "Inter, sans-serif",
            }}
          >
            {CONTENT_TYPE_LABELS[ct]}
          </button>
        ))}
      </div>

      {/* Active tab content — view mode bar is rendered by each tab after its format selector */}
      {contentType === "ownership-cost" && (
        <OwnershipCostTab
          vehicle={vehicle}
          config={config}
          format={format}
          setFormat={setFormat}
          showFinal={showFinal}
          setShowFinal={setShowFinal}
          narrationLang={narrationLang}
          setNarrationLang={setNarrationLang}
        />
      )}

      {contentType === "vehicle-review" && (
        <VehicleReviewTab
          vehicle={vehicle}
          config={config}
          format={format}
          setFormat={setFormat}
          showFinal={showFinal}
          setShowFinal={setShowFinal}
          narrationLang={narrationLang}
          setNarrationLang={setNarrationLang}
        />
      )}

      {contentType === "owner-verdict" && (
        <OwnerVerdictTab
          vehicle={activeVehicle}
          hasVerdictData={!!verdictVehicle}
          config={config}
          format={format}
          setFormat={setFormat}
          showFinal={showFinal}
          setShowFinal={setShowFinal}
          narrationLang={narrationLang}
          setNarrationLang={setNarrationLang}
        />
      )}

      {contentType === "service-bill" && (
        <ServiceBillTab
          vehicle={activeVehicle}
          billData={billData}
          config={config}
          showFinal={showFinal}
          setShowFinal={setShowFinal}
          narrationLang={narrationLang}
          setNarrationLang={setNarrationLang}
        />
      )}

      {/* Vehicle JSON (shared) */}
      <div
        style={{
          marginTop: 48,
          background: "#18181b",
          borderRadius: 12,
          padding: 20,
          border: "1px solid #27272a",
        }}
      >
        <div
          onClick={() => setJsonOpen(!jsonOpen)}
          style={{ cursor: "pointer", color: "#71717a", fontSize: 14, userSelect: "none" }}
        >
          {jsonOpen ? "\u25BC" : "\u25B6"} Vehicle JSON ({JSON.stringify(activeVehicle).length.toLocaleString()} chars)
        </div>
        {jsonOpen && (
          <pre
            style={{
              color: "#a1a1aa",
              fontSize: 12,
              marginTop: 12,
              overflowX: "auto",
              whiteSpace: "pre-wrap",
              maxHeight: 400,
              overflowY: "auto",
            }}
          >
            {JSON.stringify(activeVehicle, null, 2)}
          </pre>
        )}
      </div>
    </div>
  );
};
