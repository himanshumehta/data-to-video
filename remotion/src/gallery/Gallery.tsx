// ── Session ─────────────────────────────────────────────────────────────
// the preview step can write per-session files as current-vehicle-{session}.json etc. and
// opens the browser at /?session={session}. When ?session= is absent (e.g.
// `npm run gallery` run by hand), we fall back to the unprefixed legacy
// filenames so the bare workflow still works.

const SESSION: string | null = (() => {
  if (typeof window === "undefined") return null;
  const s = new URLSearchParams(window.location.search).get("session");
  return s && s.length > 0 ? s : null;
})();

async function fetchJSON(paths: string[]): Promise<any | null> {
  for (const p of paths) {
    try {
      const resp = await fetch(p);
      if (resp.ok) return await resp.json();
    } catch {}
  }
  return null;
}

// ── Data loaders ────────────────────────────────────────────────────────

async function loadGalleryConfig(): Promise<GalleryConfig | null> {
  const paths = SESSION
    ? [`/gallery-config-${SESSION}.json`, "/gallery-config.json"]
    : ["/gallery-config.json"];
  return fetchJSON(paths);
}

async function loadBillData(): Promise<any | null> {
  // service-bill previews are generated by a separate pipeline that still
  // writes to the unprefixed filename — leave as-is until it opts into sessions.
  return fetchJSON(["/current-bill.json"]);
}

async function loadVehicle(): Promise<Vehicle | null> {
  const paths = SESSION
    ? [`/current-vehicle-${SESSION}.json`, "/current-vehicle.json", "/preview-vehicle.json"]
    : ["/current-vehicle.json", "/preview-vehicle.json"];
  return fetchJSON(paths);
}

async function loadVerdictVehicle(): Promise<Vehicle | null> {
  const paths = SESSION
    ? [`/current-verdict-${SESSION}.json`, "/current-verdict.json"]
    : ["/current-verdict.json"];
  return fetchJSON(paths);
}

